"""Regenerate docs/error-catalog.md by compiling one example per error code.

    python scripts/gen_error_catalog.py
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from compiler import compile_source  # noqa: E402
from compiler.common.diagnostics import CATALOG  # noqa: E402

EXAMPLES = {
    "E_LEX_INVALID_CHAR": ("program", "int x = 5 @ 3;"),
    "E_LEX_MALFORMED_NUMBER": ("program", "float f = 3.;"),
    "E_LEX_UNTERMINATED_STRING": ("program", 'print("hello);'),
    "E_LEX_UNTERMINATED_COMMENT": ("program", "int x = 1; /* never closed"),
    "E_INPUT_TOO_LONG": ("expression", "1+" * 300 + "1"),
    "E_SYN_EMPTY": ("expression", ""),
    "E_SYN_UNEXPECTED_TOKEN": ("expression", "a + * b"),
    "E_SYN_UNEXPECTED_EOF": ("expression", "a +"),
    "E_SYN_EXPECTED": ("program", "if (x > 1 { }"),
    "E_SYN_MISSING_SEMICOLON": ("program", "int x = 5\nint y = 2;"),
    "E_SYN_MISSING_RPAREN": ("expression", "(a + b"),
    "E_SYN_UNMATCHED_RPAREN": ("expression", "a + b)"),
    "E_SYN_MISSING_RBRACE": ("program", "while (true) { print(1);"),
    "E_SYN_EMPTY_PARENS": ("expression", "()"),
    "E_SYN_MISSING_OPERATOR": ("expression", "2(3)"),
    "E_SYN_UNARY_NOT_SUPPORTED": ("expression", "-5"),
    "E_SYN_CHAINED_COMPARISON": ("program", "bool b = 1 < 2 < 3;"),
    "E_SYN_ELSE_WITHOUT_IF": ("program", "else { }"),
    "E_SYN_NESTED_FUNCTION": ("program", "{ int f() { return 1; } }"),
    "E_SYN_EXPECTED_STATEMENT": ("program", "5 + 3;"),
    "E_SYN_TOO_DEEP": ("expression", "(" * 101 + "1" + ")" * 101),
    "E_SYN_TOO_COMPLEX": ("program", "int x = " + " + ".join(["1"] * 220) + ";"),
    "E_SYN_TOO_MANY_ERRORS": ("program", "else;\n" * 25),
    "E_SEM_UNDECLARED": ("program", "x = 3;"),
    "E_SEM_REDECLARED": ("program", "int a = 1; int a = 2;"),
    "E_SEM_TYPE_MISMATCH": ("program", "int x = true;"),
    "E_SEM_LOSSY_ASSIGN": ("program", "int x = 1.5;"),
    "E_SEM_CONDITION_NOT_BOOL": ("program", "int x = 1; if (x) { }"),
    "E_SEM_INVALID_OPERANDS": ("program", "bool b = 1 + true;"),
    "E_SEM_NOT_A_FUNCTION": ("program", "int x = 1; x();"),
    "E_SEM_NOT_A_VARIABLE": ("program", "void f() { } int y = f + 1;"),
    "E_SEM_ARG_COUNT": ("program", "int add(int a, int b) { return a + b; } print(add(1));"),
    "E_SEM_ARG_TYPE": ("program", "int sq(int a) { return a * a; } print(sq(true));"),
    "E_SEM_RETURN_TYPE": ("program", "int f() { return true; }"),
    "E_SEM_MISSING_RETURN": ("program", "int f(int a) { if (a > 0) { return 1; } }"),
    "E_SEM_RETURN_OUTSIDE_FUNCTION": ("program", "return 1;"),
    "E_SEM_BREAK_OUTSIDE_LOOP": ("program", "break;"),
    "E_SEM_VOID_VALUE": ("program", "void f() { } int x = f();"),
    "W_SEM_UNUSED": ("program", "int unused = 1;"),
    "E_RT_DIV_ZERO": ("program", "int z = 0; print(10 / z);"),
    "E_RT_MOD_ZERO": ("program", "int z = 0; print(10 % z);"),
    "E_RT_OVERFLOW": ("program", "float f = 1.0; while (true) { f = f * 1000.0; }"),
    "E_RT_STEP_LIMIT": ("program", "while (true) { }"),
    "E_RT_OUTPUT_LIMIT": ("program", "for (;;) { print(1); }"),
    "E_RT_CALL_DEPTH": ("program", "int f(int n) { return f(n + 1); } print(f(0));"),
}


def main() -> None:
    lines = [
        "# Error catalog",
        "",
        "Generated by `python scripts/gen_error_catalog.py` — every message below is real compiler",
        "output. Positions are 1-based `line:col`.",
        "",
    ]
    phase_titles = {"E_LEX": "Lexical errors", "E_INP": "Input limits", "E_SYN": "Syntax errors",
                    "E_SEM": "Semantic errors", "W_SEM": "Warnings", "E_RT_": "Runtime errors"}
    current = None
    for code, description in CATALOG.items():
        group = phase_titles.get(code[:5], "Other")
        if group != current:
            if current is not None:
                lines.append("")
            lines += [f"## {group}", "", "| Code | Meaning | Example | Message |", "|---|---|---|---|"]
            current = group
        example, message = "", "_(internal; not expected in normal use)_"
        if code in EXAMPLES:
            mode, source = EXAMPLES[code]
            result = compile_source(source, mode)
            match = next((d for d in result["diagnostics"] if d["code"] == code), None)
            assert match is not None, f"{code} not produced by its example"
            shown = source if len(source) <= 48 else source[:45] + "…"
            example = f"`{shown}`".replace("|", "\\|").replace("\n", "⏎")
            where = f" ({match['line']}:{match['col']})" if match["line"] else ""
            message = (match["message"] + where).replace("|", "\\|")
        lines.append(f"| `{code}` | {description} | {example} | {message} |")
    out = ROOT / "docs" / "error-catalog.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
